using System.Text.Json;
using Amaquet;

namespace Amaquet.Examples;

/// <summary>Source-backed text_field example. OP calls require --operations.</summary>
public static class TypeTextField
{
    public static async Task RunAsync(AmaquetClient client, bool operations)
    {
        var handle = client.Typed.TextField("example:text_field");
        await handle.CreateAsync(
            JsonDocument
                .Parse(
                    "{\"name\":\"body\",\"value\":\"hello amaquet\",\"weight\":1.5}"
                )
                .RootElement
        );

        Console.WriteLine((await handle.ReadKeyAsync()).GetRawText());
        if (!operations)
        {
            return;
        }

        Console.WriteLine(
            (
                await handle.SetAsync(
                    JsonSerializer.Deserialize<Dictionary<string, object?>>(
                        "{\"name\":\"body\",\"value\":\"updated text\",\"weight\":2}"
                    )!
                )
            ).GetRawText()
        );

        Console.WriteLine(
            (
                await handle.GetAsync(
                    JsonSerializer.Deserialize<Dictionary<string, object?>>(
                        "{}"
                    )!
                )
            ).GetRawText()
        );
    }
}
